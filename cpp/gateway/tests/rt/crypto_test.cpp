  Bytes hex(std::string_view text) {
    Bytes out;
    for (std::size_t index = 0; index + 1 < text.size(); index += 2) out.push_back(static_cast<std::uint8_t>(std::stoi(std::string(text.substr(index, 2)), nullptr, 16)));
    return out;
  }
  std::string toHex(const Bytes& bytes) {
    static const char digits[] = "0123456789abcdef";
    std::string out;
    for (auto byte : bytes) {
      out += digits[byte >> 4];
      out += digits[byte & 15];
    }
    return out;
  }
  Bytes utf8(std::string_view text) { return Bytes(text.begin(), text.end()); }
  Bytes sequence(std::size_t length, std::uint8_t start = 0) {
    Bytes out(length);
    for (std::size_t index = 0; index < length; ++index) out[index] = static_cast<std::uint8_t>(start + index);
    return out;
  }

  // Runs `body` and returns "Name: message" of the rt::JsError it throws.
  template <class F> std::string errorOf(F body) {
    try {
      body();
    } catch (const rt::JsError& error) {
      return error.name + ": " + error.message;
    }
    return "no error";
  }

