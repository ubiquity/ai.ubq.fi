#!/usr/bin/python3
"""Generate CTest registrations from the existing Links resolver, without a second list."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True
import links
import vendor_sources

GATEWAY = Path(links.GATEWAY)
SUPPORT = ("tools/generate-tests.py", "tools/ctest-run.py", "tools/ctest_support.py", "tools/ctest-network.py")


def target_name(test):
    return "uos_test_" + hashlib.sha256(test.encode()).hexdigest()[:16]


def resolve_test(test, registry=None, vendors=None):
    registry = links.read_registry() if registry is None else registry
    runtime = sorted(path.relative_to(GATEWAY).as_posix() for path in (GATEWAY / "src/rt").glob("*.cpp")
                     if not path.name.startswith("."))
    selected = links.resolve(test, registry)
    sources = list(dict.fromkeys([test] + selected.sources + runtime))
    inputs = sorted(set(links.input_paths(test, selected.sources, vendors)) | set(SUPPORT) | {"tests/LINKS.txt"})
    for relative in sources + inputs:
        path = Path(relative)
        if path.is_absolute() or ".." in path.parts or not (GATEWAY / path).is_file():
            raise RuntimeError("Missing or nonlocal test input: " + relative)
    return {"test": test, "target": target_name(test), "sources": sources, "inputs": inputs,
            "environment": selected.env, "skip": selected.skip, "origin": selected.origin,
            "notes": selected.notes, "warnings": selected.warnings}


def inventory():
    registry = links.read_registry()
    vendors = tuple(vendor_sources.selected())
    tests = []
    for test in links.all_tests():
        tests.append(resolve_test(test, registry, vendors))
    stale = sorted(set(registry) - {item["test"] for item in tests})
    if stale:
        raise RuntimeError("Stale Links registry entries: " + ", ".join(stale))
    return {"schema": 1, "source_root": str(GATEWAY), "test_count": len(tests), "tests": tests}


def cmake_quote(value):
    if any(character in value for character in ('"', ";", "$", "\\", "\n", "\r")):
        raise RuntimeError("Unsafe CMake source path: " + value)
    return '"' + value + '"'


def cmake_text(registry):
    lines = ["# Generated by tools/generate-tests.py from links.py and the unchanged Links declarations.",
             "set(UOS_TEST_TARGETS)", "function(uos_add_registered_test target test)",
             "  set(objects)", "  foreach(source IN LISTS ARGN)",
             "    uos_object_for_source(object \"${source}\")",
             "    list(APPEND objects \"$<TARGET_OBJECTS:${object}>\")", "  endforeach()",
             "  add_executable(\"${target}\" EXCLUDE_FROM_ALL ${objects})",
             "  target_link_libraries(\"${target}\" PRIVATE uos_gateway_settings)",
             "  uos_link_vendors(\"${target}\" ${ARGN})",
             "  add_test(NAME \"${test}\" COMMAND /usr/bin/python3",
             "    \"${CMAKE_CURRENT_SOURCE_DIR}/tools/ctest-run.py\" run",
             "    --registry \"${CMAKE_CURRENT_BINARY_DIR}/tests-registry.json\" --target \"${target}\"",
             "    --binary \"$<TARGET_FILE:${target}>\" --profile-owner \"${CMAKE_CURRENT_BINARY_DIR}/profile-owner.json\")",
             "  set_tests_properties(\"${test}\" PROPERTIES RUN_SERIAL TRUE TIMEOUT 330 SKIP_RETURN_CODE 77)",
             "endfunction()", ""]
    for selected in registry["tests"]:
        lines += ["uos_add_registered_test(" + cmake_quote(selected["target"]) + " " + cmake_quote(selected["test"])]
        lines += ["  " + cmake_quote(source) for source in selected["sources"]]
        lines += [")", "list(APPEND UOS_TEST_TARGETS " + cmake_quote(selected["target"]) + ")"]
    lines += ["add_custom_target(uos_gateway_tests DEPENDS ${UOS_TEST_TARGETS})", ""]
    return "\n".join(lines)


def atomic_text(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    candidate = path.with_name(path.name + ".tmp")
    candidate.write_text(text)
    candidate.replace(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--cmake", type=Path, required=True)
    options = parser.parse_args()
    registry = inventory()
    atomic_text(options.registry, json.dumps(registry, indent=2) + "\n")
    atomic_text(options.cmake, cmake_text(registry))
    print(json.dumps({"tests": registry["test_count"], "skipped": sum(bool(item["skip"]) for item in registry["tests"]),
                      "registry": str(options.registry), "cmake": str(options.cmake)}))


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError, links.LinkError) as error:
        print("generate-tests: " + str(error), file=sys.stderr)
        raise SystemExit(2)
